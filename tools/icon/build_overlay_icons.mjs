// Embed the local Orbit and Figma SVGs so the overlay needs no page-origin asset requests.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../../", import.meta.url);
const names = ["audio", "chevron", "close", "cookie", "download", "hide", "more", "settings", "site", "subtitles", "video"];
const sources = [["logo", "art/Orbit Download Manager.svg"], ...names.map((name) => [name, `extension/assets/overlay-${name}.svg`])];
const icons = await Promise.all(sources.map(async ([name, path]) => {
  const svg = (await readFile(new URL(path, root), "utf8")).trim();
  const references = new Set(Array.from(svg.matchAll(/url\(#([^)]+)\)/g), ([, id]) => id));
  const markup = svg
    .replace(/\s+id="([^"]+)"/g, (_, id) => references.has(id) ? ` id="ORBIT_ICON_${id}"` : "")
    .replace(/url\(#([^)]+)\)/g, "url(#ORBIT_ICON_$1)")
    .replace(/>\s+</g, "><");
  return `    ${name}: ${JSON.stringify(markup)},`;
}));

const path = new URL("extension/video.js", root);
const source = await readFile(path, "utf8");
const block = /  \/\/ BEGIN VIDEO ICONS\r?\n[\s\S]*?  \/\/ END VIDEO ICONS/;
if (!block.test(source)) throw new Error("Could not find the video icon block");
const generated = source.replace(block, () => [
  "  // BEGIN VIDEO ICONS",
  "  // Generated by tools/icon/build_overlay_icons.mjs.",
  "  const VIDEO_ICONS = {",
  ...icons,
  "  };",
  "  // END VIDEO ICONS",
].join("\n"));
if (source !== generated) await writeFile(path, generated);
